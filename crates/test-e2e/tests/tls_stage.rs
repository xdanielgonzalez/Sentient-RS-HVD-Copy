//! A TLS record-layer stage (`lib_net::link::tls::TlsStage`) over the owned `NetStack`.
//!
//! `lib-security` defines the crypto *provider* seam (Verifier/Hasher/Rng/KeyStore) the stage
//! leans on conceptually, but the actual TLS record layer over an owned TCP socket lives here, atop
//! rustls 0.22. These are the two specs that define what "a TLS stage" means: a byte-vector unit
//! test (no `NetStack` involved) and a two-`NetStack` loopback handshake + one encrypted record
//! round-trip.
//!
//! ## A deliberate, disclosed change from the original TDD-RED draft
//!
//! The first test originally fed a hand-crafted, *deliberately truncated* byte vector (a TLS record
//! header declaring 5 body bytes with only 4 present, wrapping a ClientHello handshake header whose
//! own declared length also exceeded what was supplied) and asserted the server stage would still
//! emit a complete ServerHello flight in response. That assertion cannot hold against a real TLS
//! implementation: an incomplete record is — correctly — buffered by the record deframer pending
//! the rest of the bytes, so `process_new_packets` returns `Ok` (matching the original "the stage
//! should accept a well-formed (if incomplete) record" expectation) but produces *no* output, since
//! there is no complete ClientHello to respond to yet. A mock/looser implementation could fake a
//! response to a recognizable byte prefix, but that would mean this crate isn't actually running
//! rustls's handshake logic here — contrary to the point of wiring in a real TLS stack.
//!
//! The fix keeps the test's intent (a server stage, fed a real ClientHello, has a ServerHello
//! flight ready and is still mid-handshake) but generates a genuine, complete ClientHello with a
//! real client-role `TlsStage` instead of a hand-encoded byte array — which is also more robust
//! against any future change to rustls's wire encoding (cipher suite list, extensions, etc.) than a
//! magic constant would be.

// Test code opts out of the workspace's `unwrap_used`/`expect_used`/`panic` lint (production posture
// only) — same convention as the existing unit tests in this crate.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use lib_net::link::tls::{TlsStage, TLS_CHUNK};
use lib_net::link::tls_identity::{SoftwareTlsIdentity, TlsIdentity};
use rustls::pki_types::{CertificateDer, PrivateKeyDer, PrivatePkcs8KeyDer};
use smoltcp::iface::SocketStorage;
use smoltcp::socket::tcp::State;
use smoltcp::wire::{IpAddress, IpEndpoint, Ipv4Address, Ipv4Cidr};
use test_kit::LoopbackBridge;

/// A fresh, self-signed identity (generated per call — see `test_kit::tls`'s module docs) plus
/// the matching trust root [`lib_net::link::tls::TlsStage::new_client`] needs — both built from the
/// same generated certificate bytes, so a client trusting `root` and a server presenting
/// `identity` complete a genuine handshake.
fn bringup_identity() -> (SoftwareTlsIdentity, CertificateDer<'static>) {
    let generated = test_kit::generate_bringup_identity();
    let root = CertificateDer::from(generated.cert_der.clone());
    let identity = SoftwareTlsIdentity::from_der(
        CertificateDer::from(generated.cert_der),
        PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(generated.key_der)),
    )
    .expect("a freshly generated identity always builds");
    (identity, root)
}

#[test]
fn server_stage_responds_to_a_known_client_hello_prefix_with_a_handshake_record() {
    let (identity, root) = bringup_identity();

    // A real ClientHello flight, generated by our own client-role stage — see the module docs for
    // why this replaced a hand-crafted (and necessarily incomplete) byte vector.
    let mut client = TlsStage::new_client("sentient-rs.local", root);
    let mut client_hello = [0u8; TLS_CHUNK];
    let client_hello_len = client.drain_outgoing(&mut client_hello);
    assert!(
        client_hello_len > 0,
        "a fresh client stage should have a ClientHello flight ready to send"
    );

    let mut server = TlsStage::new_server(&identity).expect("bring-up identity always builds");
    server
        .feed_incoming(&client_hello[..client_hello_len])
        .expect("the stage should accept a well-formed ClientHello record");

    let mut out = [0u8; TLS_CHUNK];
    let n = server.drain_outgoing(&mut out);
    assert!(
        n > 0,
        "a server stage fed a ClientHello should have a ServerHello flight to send"
    );
    assert_eq!(
        out[0], 0x16,
        "the response's first record should be a TLS Handshake record (ContentType::Handshake)"
    );
    assert!(
        server.is_handshaking(),
        "the handshake is not complete after only a ClientHello"
    );
}

#[test]
fn client_and_server_stages_complete_a_handshake_and_round_trip_one_record_over_loopback() {
    const CLIENT_MAC: [u8; 6] = [0x02, 0x00, 0x00, 0x00, 0x00, 0x03];
    const SERVER_MAC: [u8; 6] = [0x02, 0x00, 0x00, 0x00, 0x00, 0x04];
    const CLIENT_IP: Ipv4Address = Ipv4Address::new(10, 0, 1, 1);
    const SERVER_IP: Ipv4Address = Ipv4Address::new(10, 0, 1, 2);
    const SERVER_PORT: u16 = 8443;
    const CLIENT_PORT: u16 = 55001;
    const PLAINTEXT: &[u8] = b"tls-loopback-record";
    const MAX_POLLS: usize = 500;

    let (mut device_client, mut device_server) = LoopbackBridge::new(1514).split();

    let mut client_sockets: [SocketStorage; 1] = Default::default();
    let mut server_sockets: [SocketStorage; 1] = Default::default();
    let mut client_stack = lib_net::link::NetStack::new(
        &mut device_client,
        CLIENT_MAC,
        Ipv4Cidr::new(CLIENT_IP, 24),
        None,
        &mut client_sockets,
    );
    let mut server_stack = lib_net::link::NetStack::new(
        &mut device_server,
        SERVER_MAC,
        Ipv4Cidr::new(SERVER_IP, 24),
        None,
        &mut server_sockets,
    );

    let mut client_rx = [0u8; 4096];
    let mut client_tx = [0u8; 4096];
    let mut server_rx = [0u8; 4096];
    let mut server_tx = [0u8; 4096];
    let client_handle = client_stack.add_tcp(&mut client_rx, &mut client_tx);
    let server_handle = server_stack.add_tcp(&mut server_rx, &mut server_tx);

    server_stack
        .tcp(server_handle)
        .listen(SERVER_PORT)
        .expect("server can listen");
    client_stack
        .connect(
            client_handle,
            IpEndpoint::new(IpAddress::Ipv4(SERVER_IP), SERVER_PORT),
            CLIENT_PORT,
        )
        .expect("client can initiate a connection");

    let mut now_ms: i64 = 0;
    while client_stack.tcp(client_handle).state() != State::Established
        || server_stack.tcp(server_handle).state() != State::Established
    {
        client_stack.poll(&mut device_client, now_ms);
        server_stack.poll(&mut device_server, now_ms);
        now_ms += 10;
    }

    let (identity, root) = bringup_identity();
    let mut tls_client = TlsStage::new_client("sentient-rs.local", root);
    let mut tls_server = TlsStage::new_server(&identity).expect("bring-up identity always builds");

    let mut io_buf = [0u8; TLS_CHUNK];
    let mut handshaking = true;
    for _ in 0..MAX_POLLS {
        client_stack.poll(&mut device_client, now_ms);
        server_stack.poll(&mut device_server, now_ms);

        // Pump TLS bytes: TCP socket -> TLS stage -> drain -> peer's TCP socket, both directions.
        if client_stack.tcp(client_handle).can_recv() {
            let n = client_stack
                .tcp(client_handle)
                .recv_slice(&mut io_buf)
                .expect("client TCP recv");
            tls_client
                .feed_incoming(&io_buf[..n])
                .expect("client TLS stage accepts the peer's flight");
        }
        let n = tls_client.drain_outgoing(&mut io_buf);
        if n > 0 {
            client_stack
                .tcp(client_handle)
                .send_slice(&io_buf[..n])
                .expect("client TCP send");
        }

        if server_stack.tcp(server_handle).can_recv() {
            let n = server_stack
                .tcp(server_handle)
                .recv_slice(&mut io_buf)
                .expect("server TCP recv");
            tls_server
                .feed_incoming(&io_buf[..n])
                .expect("server TLS stage accepts the peer's flight");
        }
        let n = tls_server.drain_outgoing(&mut io_buf);
        if n > 0 {
            server_stack
                .tcp(server_handle)
                .send_slice(&io_buf[..n])
                .expect("server TCP send");
        }

        now_ms += 10;
        if !tls_client.is_handshaking() && !tls_server.is_handshaking() {
            handshaking = false;
            break;
        }
    }
    assert!(
        !handshaking,
        "client and server TLS stages should complete a handshake over the TCP loopback"
    );

    tls_client
        .write_plaintext(PLAINTEXT)
        .expect("client can queue plaintext for a sealed record");
    let mut plaintext_out = [0u8; 256];
    let mut got = 0usize;
    for _ in 0..MAX_POLLS {
        client_stack.poll(&mut device_client, now_ms);
        server_stack.poll(&mut device_server, now_ms);

        let n = tls_client.drain_outgoing(&mut io_buf);
        if n > 0 {
            client_stack
                .tcp(client_handle)
                .send_slice(&io_buf[..n])
                .expect("client TCP send");
        }
        if server_stack.tcp(server_handle).can_recv() {
            let n = server_stack
                .tcp(server_handle)
                .recv_slice(&mut io_buf)
                .expect("server TCP recv");
            tls_server
                .feed_incoming(&io_buf[..n])
                .expect("server TLS stage accepts the sealed record");
        }
        got = tls_server
            .read_plaintext(&mut plaintext_out)
            .expect("server TLS stage can decrypt the record");
        if got > 0 {
            break;
        }
        now_ms += 10;
    }
    assert_eq!(
        &plaintext_out[..got],
        PLAINTEXT,
        "the encrypted record's plaintext should round-trip byte-exact"
    );
}

#[test]
fn default_identity_reports_software_custody() {
    let (identity, _root) = bringup_identity();
    assert_eq!(
        identity.custody(),
        lib_security::KeyCustody::SoftwareMemory,
        "the bring-up identity's key lives in process memory, not a secure element — it must never \
         claim otherwise"
    );
}

/// A `KeyStore` stub that claims secure-world custody but never actually signs — mirrors
/// `lib-security`'s current posture (`KeyStore::sign`/`generate` are fail-closed
/// `NotImplemented` stubs; see `lib-security/src/provider.rs`). Exists only to prove
/// [`KeyStoreTlsIdentity`] is a structurally distinct path from [`SoftwareTlsIdentity`] — the point
/// is the seam, not that hardware signing works yet.
#[derive(Debug)]
struct StubSecureWorldKeyStore;

impl lib_security::KeyStore for StubSecureWorldKeyStore {
    fn custody(&self) -> lib_security::KeyCustody {
        lib_security::KeyCustody::SecureWorld
    }

    fn generate(
        &mut self,
        _algorithm: lib_security::Algorithm,
    ) -> lib_security::Result<lib_security::KeyHandle> {
        Err(lib_security::SecurityError::NotImplemented)
    }

    fn import_private(
        &mut self,
        _algorithm: lib_security::Algorithm,
        _bytes: &[u8],
    ) -> lib_security::Result<lib_security::KeyHandle> {
        Err(lib_security::SecurityError::NotImplemented)
    }

    fn export_public(
        &self,
        _handle: lib_security::KeyHandle,
        _out: &mut [u8],
    ) -> lib_security::Result<usize> {
        Err(lib_security::SecurityError::NotImplemented)
    }

    fn sign(
        &self,
        _handle: lib_security::KeyHandle,
        _message: &[u8],
        _out: &mut [u8],
    ) -> lib_security::Result<usize> {
        Err(lib_security::SecurityError::NotImplemented)
    }
}

#[test]
fn keystore_backed_identity_is_a_structurally_distinct_path_from_software() {
    use lib_net::link::tls_identity::KeyStoreTlsIdentity;

    let store = std::sync::Arc::new(StubSecureWorldKeyStore);
    let handle = lib_security::KeyHandle(1);
    // A freshly generated certificate (see `test_kit::tls`'s module docs) reused as filler cert
    // material — this test never drives a real handshake with it, so the cert doesn't need to
    // attest to the stub store's (nonexistent) key; it only needs to be well-formed DER for
    // `CertifiedKey::new`.
    let cert_chain = vec![CertificateDer::from(
        test_kit::generate_bringup_identity().cert_der,
    )];
    let identity = KeyStoreTlsIdentity::new(
        store,
        handle,
        lib_security::Algorithm::EcdsaP256Sha256,
        cert_chain,
    );

    assert_eq!(
        identity.custody(),
        lib_security::KeyCustody::SecureWorld,
        "custody flows straight through from the KeyStore, distinct from the software identity"
    );

    // Building the certified key doesn't need to sign anything yet (signing happens lazily, only
    // if a real handshake asks for a signature) — so this succeeds even though the stub store's
    // `sign` is a `NotImplemented` stub.
    let certified = identity
        .certified_key()
        .expect("building a certified key doesn't invoke KeyStore::sign");
    assert_eq!(certified.cert.len(), 1);

    // The whole point of the seam: this plugs into TlsStage exactly like the software identity,
    // with no change to TlsStage's code.
    assert!(
        TlsStage::new_server(&identity).is_ok(),
        "a KeyStore-backed identity constructs a server stage the same way the software one does"
    );
}
