// Copies `memory.x` into OUT_DIR and wires the linker args cortex-m-rt/embassy-rp expect. For
// RP2350A, embassy-rp-0.10.0 auto-generates the IMAGE_DEF block, so no explicit boot2 handling is
// needed (unlike RP2040). Mirrors hil/pico-seplos-emu/build.rs.
//
// Under feature `veneers`, also links the S-world veneer import artifact (`s` crate's build.rs):
// resolved via `SENTIENT_VENEER_IMPLIB` env var if set, else the frozen fallback path
// `bin/mcu-rp2350/target/veneer-implib/libveneer_implib.o`.

use std::env;
use std::fs::File;
use std::io::Write;
use std::path::PathBuf;

fn main() {
    let out = &PathBuf::from(env::var_os("OUT_DIR").unwrap());

    // Flash/RAM origin depends on the boot topology:
    //   - `veneers` OFF (default, incl. the W5500 broker bench): this IS the whole image. The boot
    //     ROM scans the first 4 KiB at the chip's real 0x10000000 for the IMAGE_DEF, so the image
    //     MUST be based there — otherwise a bare board drops to BOOTSEL and never runs. Full 8 MiB
    //     flash (0x800000, the Adafruit Feather RP2350's QSPI window) / 512 KiB SRAM.
    //   - `veneers` ON (Stage 4 S/NS split, #355): the `s` (secure) image owns 0x10000000 + the
    //     first 128 KiB / 64 KiB; the boot ROM boots `s`, which `bxns`-jumps here. This NS half is
    //     based past the S region (0x10020000 / 0x20010000) and runs to the same 8 MiB ceiling
    //     (0x10020000 + 0x7E0000 == 0x10800000). See `../s/memory.x`.
    // RAM is unchanged by the Pico-2-to-Feather board move: both arms claim a 512 KiB SRAM window,
    // deliberately leaving the chip's top 8 KiB (0x20080000..0x20082000 of its contiguous 520 KiB)
    // unclaimed — see `../s/src/mem_layout.rs`'s `NS_RAM_END` doc for why that is on purpose.
    //
    // SOURCE OF TRUTH / KNOWN WART: `../s/src/mem_layout.rs` is the intended single Rust-side source
    // of truth for the S/NS split (`S_FLASH_*`, `NS_FLASH_*`, `S_RAM_*`, `NS_RAM_*`). This build
    // script currently DUPLICATES those values as string literals rather than deriving them, because
    // a build script cannot `use` a constant out of a different crate's `src/`. The duplication is a
    // real wart — an edit to `mem_layout.rs` alone will silently not reach the linker script this
    // file writes. To be refactored (share the numbers via a tiny no-`std` const crate or a generated
    // include both sides read); until then, any change here must be mirrored there and in `memory.x`.
    let veneers = env::var("CARGO_FEATURE_VENEERS").is_ok();
    let (flash_origin, flash_len, ram_origin, ram_len) = if veneers {
        ("0x10020000", "0x7E0000", "0x20010000", "0x70000")
    } else {
        ("0x10000000", "0x800000", "0x20000000", "0x80000")
    };
    let memory_x = format!(
        "/* @generated by build.rs from the `veneers` feature — do not edit; see memory.x + build.rs. */\n\
         MEMORY {{\n    \
             FLASH : ORIGIN = {flash_origin}, LENGTH = {flash_len}\n    \
             RAM   : ORIGIN = {ram_origin}, LENGTH = {ram_len}\n\
         }}\n\n\
         /* IMAGE_DEF (.start_block) between the vector table and .text, in the first 4 KiB of this\n\
            image's own FLASH region. embassy-rp's `_rp235x` feature always emits `.start_block`, so\n\
            it always needs placement or the link fails on an orphan section. */\n\
         SECTIONS {{\n    \
             .start_block (ADDR(.vector_table) + SIZEOF(.vector_table)) : ALIGN(4) {{\n        \
                 __start_block_addr = .;\n        \
                 KEEP(*(.start_block));\n        \
                 _stext_offset = .;\n    \
             }} > FLASH\n\
         }} INSERT BEFORE .text;\n\n\
         _stext = _stext_offset;\n"
    );
    File::create(out.join("memory.x"))
        .unwrap()
        .write_all(memory_x.as_bytes())
        .unwrap();
    println!("cargo:rustc-link-search={}", out.display());
    println!("cargo:rerun-if-changed=memory.x");
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_VENEERS");

    // `boot_w5500.rs`'s `HOSTNAME` is baked in at compile time via `option_env!("DEVICE_HOSTNAME")`
    // (default `meteor-pico`; the justfile `mcu-flash-device` recipe passes an override). `option_env!`
    // is not tracked by cargo's fingerprint on its own, so trigger a rebuild when the value changes —
    // otherwise a re-flash with a new `DEVICE_HOSTNAME` would silently ship the previously-baked name.
    println!("cargo:rerun-if-env-changed=DEVICE_HOSTNAME");

    println!("cargo:rustc-link-arg-bins=--nmagic");
    println!("cargo:rustc-link-arg-bins=-Tlink.x");

    // link-rp.x is only generated (and needed) for RP2040. RP235x uses the default cortex-m-rt linkage.
    if env::var("CARGO_FEATURE_RP2040").is_ok() {
        println!("cargo:rustc-link-arg-bins=-Tlink-rp.x");
    }

    // Under the `defmt` feature, `main.rs` links the defmt-rtt `#[global_logger]`, which emits its
    // interned log strings into a `.defmt` linker section that `defmt.x` (shipped by the `defmt`
    // crate to its OUT_DIR / the link search path) lays out. Without this arg the link fails on the
    // undefined `.defmt` section symbols. Guard on the feature so the default (non-defmt) build never
    // references a script it doesn't produce.
    if env::var("CARGO_FEATURE_DEFMT").is_ok() {
        println!("cargo:rustc-link-arg-bins=-Tdefmt.x");
    }

    // Stage 4 (#355) `veneers`: link the S-world veneer import artifact. Only active when the
    // feature is actually on — a `veneers`-off build never reruns/relies on this env var or the
    // fallback path, so it stays untouched by either.
    if env::var("CARGO_FEATURE_VENEERS").is_ok() {
        println!("cargo:rerun-if-env-changed=SENTIENT_VENEER_IMPLIB");
        let implib: PathBuf = match env::var("SENTIENT_VENEER_IMPLIB") {
            Ok(v) if !v.is_empty() => PathBuf::from(v),
            _ => {
                // Frozen fallback (see `../s/build.rs`'s doc comment, the artifact's producer):
                // workspace-relative, NOT under any per-profile OUT_DIR, so it survives across
                // debug/release and doesn't move when `s`'s build script re-runs.
                let manifest_dir = PathBuf::from(
                    env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR set by cargo"),
                );
                manifest_dir
                    .join("..")
                    .join("target")
                    .join("veneer-implib")
                    .join("libveneer_implib.o")
            }
        };

        // **CRITICAL**: Always emit a rerun-if-changed trigger, even if the implib doesn't exist yet.
        // Without this, cargo caches the build script result on first run. If the implib is created
        // later (e.g., by building `s` afterward), cargo would NOT re-run this script without an
        // explicit trigger on the implib path — leaving the link step unable to find the newly-created
        // artifact. This ensures fresh sequences (build ns before s, or vice versa) both work.
        println!("cargo:rerun-if-changed={}", implib.display());

        if implib.exists() {
            println!("cargo:rustc-link-arg-bins={}", implib.display());
        } else {
            // Do not hard-fail the build script itself: let `cargo build --features veneers`
            // proceed to the link step, where undefined `sv_*` symbols are a clear, honest
            // failure signal — rather than a build.rs panic that looks like a `ns`-side bug
            // before the S-side artifact (built by the separate `s` crate) has ever been
            // produced. Build `s` first (or set `SENTIENT_VENEER_IMPLIB`) to resolve this.
            println!(
                "cargo:warning=feature \"veneers\" is on but no veneer artifact was found at {} \
                 (build `s` first, or set SENTIENT_VENEER_IMPLIB) — sv_* symbols will be \
                 undefined at link time",
                implib.display()
            );
        }
    }
}
