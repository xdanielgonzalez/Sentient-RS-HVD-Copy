//! Chain-emitter tests: the `chain_topics` transitive closure, the emitted module surface, and a
//! full-IDL emit round-trip (generation itself `syn::parse2`s + prettyplease-formats, so a
//! successful `generate` proves the output is valid Rust).
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::path::PathBuf;

use tms_idl_codegen::emit_fields::chain_closure;
use tms_idl_codegen::overrides::Overrides;

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .to_path_buf()
}

fn overrides_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tms-overrides.toml")
}

#[test]
fn chain_closure_reaches_expected_nested_structs() {
    let root = repo_root();
    let gen = tms_idl_codegen::generate(&root, &overrides_path()).expect("full IDL parses clean");
    let overrides = Overrides::load(&overrides_path().to_string_lossy()).unwrap();
    let closure = chain_closure(&gen.model, &overrides.subset.chain_topics).unwrap();

    // Roots themselves.
    for root_ty in [
        "DcMeasurementUpdate",
        "PowerHardwareUpdate",
        "ActiveDiagnosticState",
        "AcMeasurementUpdate",
        "StorageUpdate",
        "DeviceInfo",
        "Reply",
        "Heartbeat",
        "PowerPortState",
        "EnergyStartStopState",
        "DcLoadSharingState",
        "ActiveMicrogridControllerState",
    ] {
        assert!(closure.contains(root_ty), "closure missing root {root_ty}");
    }
    // Transitively referenced nested structs (via Ref + Seq element types).
    for nested in [
        "StorageCellState",       // PowerHardwareUpdate -> EnergyStorageState -> storage_cells
        "DiagnosticTroubleCode",  // ActiveDiagnosticState -> codes
        "ProductInfo",            // DeviceInfo -> product
        "Curve2D",                // StorageUpdate -> charge_time
        "Point2D",                // Curve2D -> points
        "ClockMonotonic",         // DcMeasurementUpdate -> time_measured
        "DcPowerLineMeasurement", // DcMeasurementUpdate -> external_measurement -> line
        "ReplyStatus",            // Reply -> status
        "PowerPortId",            // PowerPortState -> power_ports -> connection
        "LoadStepResponse",       // DeviceInfo -> ... -> LoadSharingInfo -> load_response
    ] {
        assert!(closure.contains(nested), "closure missing nested {nested}");
    }
    // Enums never get a module; non-published topics stay out.
    assert!(!closure.contains("DtcSeverity"));
    assert!(!closure.contains("DeviceIcon"));
}

#[test]
fn emitted_fields_have_expected_surface() {
    let root = repo_root();
    let gen = tms_idl_codegen::generate(&root, &overrides_path()).expect("full IDL parses clean");
    let out = &gen.generated_fields;

    assert!(out.starts_with("// @generated by tms-idl-codegen"));
    assert!(out.contains("pub trait DcMeasurementUpdateSrc"));
    assert!(out.contains("pub mod dc_measurement_update_fields"));
    assert!(out.contains("pub type Chain"));
    assert!(out.contains("impl crate::fields::HasChain for crate::generated::DcMeasurementUpdate"));
    assert!(out.contains("impl crate::fields::HasChain for crate::generated::DeviceInfo"));
    // The compiler-forced shapes (see emit_fields.rs doc): qualified KEY + Absent empty iterator.
    assert!(out.contains("<Self as Field<Src>>::KEY"));
    assert!(out.contains("core::iter::empty()"));
    // Omit policy artifacts: let-else early return for optional scalars, has_x for optional seqs.
    assert!(out.contains("else { return };") || out.contains("else {\n            return;\n        };") || out.contains("return;"));
    assert!(out.contains("fn has_extension_topics"));

    // Keep a copy for inspection (NOT under crates/ — the main loop wires the real file).
    let tmp = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join("generated_fields.rs");
    std::fs::write(&tmp, out).unwrap();
}
