//! Emit the traceability / compliance report from the registry model — per topic and per type,
//! with provenance (IDL line), units/ranges, key fields, extensibility, and (per topic) the D.5 QoS
//! profile. This is the IDL-side view; the golden<->factory convergence is asserted by the
//! validation tests.

use crate::model::{Model, RExtensibility, RKind, RType};

pub fn emit_report(model: &Model) -> (String, String) {
    (emit_json(model), emit_md(model))
}

fn extensibility_str(e: RExtensibility) -> &'static str {
    match e {
        RExtensibility::Final => "FINAL",
        RExtensibility::Appendable => "APPENDABLE",
        RExtensibility::Mutable => "MUTABLE",
    }
}

fn emit_json(model: &Model) -> String {
    let mut out = String::new();
    out.push_str("{\n  \"_generated\": \"by tms-idl-codegen from docs/compliance/tms/mil-std-3071_data_model.idl — DO NOT EDIT; regenerate with `just tms-codegen`\",\n");
    out.push_str("  \"types\": [\n");
    let structs: Vec<&RType> = model
        .types
        .iter()
        .filter(|t| t.kind == RKind::Struct)
        .collect();
    for (i, t) in structs.iter().enumerate() {
        let units = t.fields.iter().filter(|f| f.unit.is_some()).count();
        let ranges = t.fields.iter().filter(|f| f.range.is_some()).count();
        let keys = t.fields.iter().filter(|f| f.is_key).count();
        let optionals = t.fields.iter().filter(|f| f.optional).count();
        out.push_str(&format!(
            "    {{ \"name\": \"{}\", \"module\": \"{}\", \"idl_line\": {}, \"topics\": [{}], \
             \"fields\": {}, \"keys\": {}, \"optional\": {}, \"units\": {}, \"ranges\": {}, \
             \"extensibility\": \"{}\" }}{}\n",
            t.name,
            t.module,
            t.idl_line,
            t.topics
                .iter()
                .map(|s| format!("\"{s}\""))
                .collect::<Vec<_>>()
                .join(", "),
            t.fields.len(),
            keys,
            optionals,
            units,
            ranges,
            extensibility_str(t.extensibility),
            if i + 1 < structs.len() { "," } else { "" },
        ));
    }
    out.push_str("  ],\n  \"topic_qos\": [\n");
    for (i, q) in model.topic_qos.iter().enumerate() {
        out.push_str(&format!(
            "    {{ \"topic\": \"{}\", \"profile\": \"{}\" }}{}\n",
            q.topic,
            q.profile.ident(),
            if i + 1 < model.topic_qos.len() { "," } else { "" },
        ));
    }
    out.push_str("  ]\n}\n");
    out
}

fn emit_md(model: &Model) -> String {
    let structs: Vec<&RType> = model
        .types
        .iter()
        .filter(|t| t.kind == RKind::Struct)
        .collect();
    let enums = model.types.iter().filter(|t| t.kind == RKind::Enum).count();
    let qos_by_topic: std::collections::HashMap<&str, &str> = model
        .topic_qos
        .iter()
        .map(|q| (q.topic.as_str(), q.profile.ident()))
        .collect();
    let mut topic_rows: Vec<(String, String, u32, &str)> = Vec::new();
    for t in &structs {
        for topic in &t.topics {
            topic_rows.push((
                topic.clone(),
                format!("{}::{}", t.module, t.name),
                t.idl_line,
                qos_by_topic.get(topic.as_str()).copied().unwrap_or("?"),
            ));
        }
    }
    topic_rows.sort();

    let mut out = String::new();
    out.push_str("<!-- @generated by tms-idl-codegen — DO NOT EDIT. Regenerate with `just tms-codegen`. -->\n");
    out.push_str("# TMS type-catalogue traceability report\n\n");
    out.push_str(
        "GENERATED by `tools/tms-idl-codegen` from the MIL-STD-3071 IDL — the catalogue's\n",
    );
    out.push_str(
        "single source of truth. Every row is derived from the IDL (provenance = `idl_line`).\n\n",
    );
    out.push_str(&format!(
        "- Structs in catalogue: **{}**\n- Enums in catalogue: **{}**\n- Topic bindings: **{}**\n\n",
        structs.len(),
        enums,
        topic_rows.len()
    ));
    out.push_str("## Topics -> type (provenance)\n\n");
    out.push_str("| Topic | Type | IDL line | QoS Profile |\n|---|---|---|---|\n");
    for (topic, ty, line, profile) in &topic_rows {
        out.push_str(&format!("| `{topic}` | `{ty}` | {line} | {profile} |\n"));
    }
    out.push('\n');
    out.push_str("## Types with units / ranges (compliance metadata derived from the IDL)\n\n");
    out.push_str("| Type | Fields | @unit | @range | @key | @optional | Extensibility | IDL line |\n");
    out.push_str("|---|---|---|---|---|---|---|---|\n");
    for t in &structs {
        let units = t.fields.iter().filter(|f| f.unit.is_some()).count();
        let ranges = t.fields.iter().filter(|f| f.range.is_some()).count();
        let keys = t.fields.iter().filter(|f| f.is_key).count();
        let opts = t.fields.iter().filter(|f| f.optional).count();
        out.push_str(&format!(
            "| `{}` | {} | {} | {} | {} | {} | {} | {} |\n",
            t.name,
            t.fields.len(),
            units,
            ranges,
            keys,
            opts,
            extensibility_str(t.extensibility),
            t.idl_line
        ));
    }
    out
}
