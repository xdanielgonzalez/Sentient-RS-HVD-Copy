//! Emit the per-topic field CHAINS — `crates/lib-tms/src/generated_fields.rs`: for every struct in
//! the `[subset] chain_topics` transitive closure, a `pub mod <snake>_fields` holding a `<T>Src`
//! accessor trait (one method per IDL field, in IDL order), a forwarding impl for `&S`, an
//! uninhabited [`Absent`] impl, an IDENTITY impl for the concrete `crate::generated::<T>`, one
//! zero-sized [`Field`] marker per field, and the `Chain` type-level node list — plus a `HasChain`
//! impl binding each concrete type to its chain.
//!
//! Why a chain, not serde: the chain emits through `JsonSink` (the flat T3-safe sink), so a topic
//! can be rendered from ANY source that implements the `<T>Src` accessors — the concrete struct
//! (identity impl) or a borrowed canonical binding — without materializing the TMS struct. The
//! omit policy is structural: an absent `@optional` field's `Field::emit` returns WITHOUT touching
//! `first`, so the comma logic can never emit `null` placeholders.
//!
//! Pattern proven by a hand-written POC before being encoded here (the compiler-forced shapes):
//! * `Self::KEY` inside the blanket `impl<Src: <T>Src + ?Sized> Field<Src>` is ambiguous (E0283) —
//!   the emit body must spell `<Self as Field<Src>>::KEY`.
//! * `Absent`'s RPITIT sequence methods cannot use `match *self {}` (no hidden type to infer for
//!   the opaque `impl Iterator`) — they return `core::iter::empty()`.
//! * Forwarding GATs are `type X<'a> = S::X<'a> where Self: 'a;` and RPITIT bodies `(**self).x()`
//!   — the reborrow unifies the caller's elided lifetime with `S`'s opaque return.

use std::collections::HashSet;

use proc_macro2::{Ident, Literal, Span, TokenStream};
use quote::quote;

use crate::emit_types;
use crate::model::{Model, RField, RFieldType, RKind, RType};
use crate::overrides::Overrides;

/// Assemble the `lib-tms` `@generated` chains file for the `[subset] chain_topics` closure.
pub fn emit_fields(model: &Model, overrides: &Overrides) -> Result<String, String> {
    let roots = &overrides.subset.chain_topics;
    if roots.is_empty() {
        return Err("manifest [subset] chain_topics is empty".into());
    }
    let colliding = emit_types::colliding_names(model);
    let closure = chain_closure(model, roots)?;

    let mut modules = Vec::new();
    let mut has_chain = Vec::new();
    for t in model.types.iter().filter(|t| {
        t.kind == RKind::Struct && closure.contains(&emit_types::rust_type_name(&t.module, &t.name, &colliding))
    }) {
        let rn = emit_types::rust_type_name(&t.module, &t.name, &colliding);
        modules.push(emit_module(model, t, &rn)?);
        let modid = mod_ident(&rn);
        let tid = Ident::new(&rn, Span::call_site());
        has_chain.push(quote! {
            impl crate::fields::HasChain for crate::generated::#tid {
                type Chain = #modid::Chain;
            }
        });
    }

    let items = quote! {
        #(#modules)*
        #(#has_chain)*
    };

    let file =
        syn::parse2::<syn::File>(items).map_err(|e| format!("emitted chains invalid: {e}"))?;
    let formatted = prettyplease::unparse(&file);
    Ok(format!(
        "// @generated by tms-idl-codegen — DO NOT EDIT.\n\
         //! Generated per-topic field chains — one `<snake>_fields` module per struct in the\n\
         //! `tms-overrides.toml` `[subset] chain_topics` transitive closure: the `<T>Src` accessor\n\
         //! trait (one method per IDL field, IDL order), the `&S` forwarding impl, the `Absent`\n\
         //! impl, the identity impl for the concrete generated type, one ZST `Field` per field,\n\
         //! and the `Chain` node list (+ a `HasChain` impl per concrete type).\n\
         //!\n\
         //! Source: `docs/compliance/tms/mil-std-3071_data_model.idl` (MIL-STD-3071 TMS 2.0.2) +\n\
         //! `tms-overrides.toml` (the chain-topic subset). Regenerate with `just tms-codegen`;\n\
         //! `just tms-codegen-check` fails if this file is stale.\n\
         //!\n\
         //! Omit policy: an absent `@optional` field emits NOTHING (its `Field::emit` returns\n\
         //! without touching `first`); a present-but-NaN optional float is `Some(FloatVal::Null)`\n\
         //! and emits `key:null`. Enums emit as their quoted `wire_str()` token.\n\
         #![allow(clippy::all)]\n\
         #![allow(rustdoc::all)]\n\
         #![cfg_attr(rustfmt, rustfmt::skip)]\n\n{formatted}"
    ))
}

// ---- closure -------------------------------------------------------------------------------------

/// The transitive closure of STRUCT types reachable from the `chain_topics` roots through `Ref`
/// fields and `Seq` element types (enums are excluded — they emit via `wire_str()` and need no
/// module). Returned as the set of RUST type names. Roots match a type by its Rust name or by any
/// of its `@topic` strings.
pub fn chain_closure(model: &Model, roots: &[String]) -> Result<HashSet<String>, String> {
    let colliding = &emit_types::colliding_names(model);
    let mut out: HashSet<String> = HashSet::new();
    let mut work: Vec<&RType> = Vec::new();
    for root in roots {
        let t = model
            .types
            .iter()
            .find(|t| {
                t.kind == RKind::Struct
                    && (emit_types::rust_type_name(&t.module, &t.name, colliding) == *root
                        || t.topics.iter().any(|topic| topic == root))
            })
            .ok_or_else(|| format!("[subset] chain_topics root `{root}` is not a model struct"))?;
        work.push(t);
    }
    while let Some(t) = work.pop() {
        let rn = emit_types::rust_type_name(&t.module, &t.name, colliding);
        if !out.insert(rn) {
            continue;
        }
        for f in &t.fields {
            for r in referenced_structs(model, &f.ty)? {
                work.push(r);
            }
        }
    }
    Ok(out)
}

/// The struct types a field type references (through one `Seq` level; the IDL has no seq-of-seq).
fn referenced_structs<'a>(
    model: &'a Model,
    ty: &RFieldType,
) -> Result<Vec<&'a RType>, String> {
    match ty {
        RFieldType::Ref(r) => {
            let t = find_ref(model, r).ok_or_else(|| format!("unresolved ref `{r}`"))?;
            Ok(if t.kind == RKind::Struct { vec![t] } else { vec![] })
        }
        RFieldType::Seq(elem, _) => match &**elem {
            RFieldType::Seq(..) => Err("sequence-of-sequence unsupported by chain emitter".into()),
            other => referenced_structs(model, other),
        },
        _ => Ok(vec![]),
    }
}

/// Resolve a `Ref` string (`Name` or `leaf::Name`, as the resolver qualifies collisions) to its type.
fn find_ref<'a>(model: &'a Model, refstr: &str) -> Option<&'a RType> {
    match refstr.rsplit_once("::") {
        Some((leaf, simple)) => model
            .types
            .iter()
            .find(|t| t.name == simple && module_leaf(&t.module) == leaf),
        None => model.types.iter().find(|t| t.name == refstr),
    }
}

fn module_leaf(module: &str) -> &str {
    module.rsplit("::").next().unwrap_or(module)
}

// ---- naming --------------------------------------------------------------------------------------

fn to_snake(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    let mut out = String::with_capacity(s.len() + 4);
    for (i, &c) in chars.iter().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 && (chars[i - 1].is_ascii_lowercase() || chars[i - 1].is_ascii_digit()) {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

fn pascal(s: &str) -> String {
    let mut out = String::new();
    for seg in s.split('_') {
        let mut ch = seg.chars();
        if let Some(f) = ch.next() {
            out.push(f.to_ascii_uppercase());
            out.extend(ch.map(|c| c.to_ascii_lowercase()));
        }
    }
    out
}

fn mod_ident(rust_name: &str) -> Ident {
    Ident::new(&format!("{}_fields", to_snake(rust_name)), Span::call_site())
}

fn src_trait_ident(rust_name: &str) -> Ident {
    Ident::new(&format!("{rust_name}Src"), Span::call_site())
}

/// A field/method identifier, raw-escaped if it collides with a Rust keyword.
fn safe_ident(s: &str) -> Ident {
    match syn::parse_str::<Ident>(s) {
        Ok(id) => id,
        Err(_) => Ident::new_raw(s, Span::call_site()),
    }
}

/// The Rust type name a resolved `Ref` points at (mirrors `emit_types::ref_rust_name`).
fn ref_rust_name(refstr: &str) -> String {
    match refstr.rsplit_once("::") {
        Some((leaf, simple)) => {
            let mut c = leaf.chars();
            let cap = match c.next() {
                Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
                None => String::new(),
            };
            format!("{cap}{simple}")
        }
        None => refstr.to_string(),
    }
}

// ---- field classification --------------------------------------------------------------------------

/// A field's accessor/emit shape. `Enum`/`Struct` carry the referenced type's RUST name.
enum Kind {
    Str,
    Int,
    Bool,
    F32,
    F64,
    Enum(String),
    Struct(String),
    SeqStruct(String),
    SeqEnum(String),
    SeqStr(u32),
    SeqF32,
    SeqF64,
    SeqInt(TokenStream),
    SeqBool,
}

fn int_elem_tokens(ty: &RFieldType) -> Option<TokenStream> {
    Some(match ty {
        RFieldType::U8 => quote!(u8),
        RFieldType::U16 => quote!(u16),
        RFieldType::U32 => quote!(u32),
        RFieldType::U64 => quote!(u64),
        RFieldType::I16 => quote!(i16),
        RFieldType::I32 => quote!(i32),
        _ => return None,
    })
}

fn classify(model: &Model, ty: &RFieldType) -> Result<Kind, String> {
    Ok(match ty {
        RFieldType::Str(_) => Kind::Str,
        RFieldType::F32 => Kind::F32,
        RFieldType::F64 => Kind::F64,
        RFieldType::Bool => Kind::Bool,
        RFieldType::U8
        | RFieldType::U16
        | RFieldType::U32
        | RFieldType::U64
        | RFieldType::I16
        | RFieldType::I32 => Kind::Int,
        RFieldType::Ref(r) => {
            let t = find_ref(model, r).ok_or_else(|| format!("unresolved ref `{r}`"))?;
            match t.kind {
                RKind::Enum => Kind::Enum(ref_rust_name(r)),
                RKind::Struct => Kind::Struct(ref_rust_name(r)),
            }
        }
        RFieldType::Seq(elem, _) => match &**elem {
            RFieldType::Str(n) => Kind::SeqStr(*n),
            RFieldType::F32 => Kind::SeqF32,
            RFieldType::F64 => Kind::SeqF64,
            RFieldType::Bool => Kind::SeqBool,
            RFieldType::Ref(r) => {
                let t = find_ref(model, r).ok_or_else(|| format!("unresolved ref `{r}`"))?;
                match t.kind {
                    RKind::Enum => Kind::SeqEnum(ref_rust_name(r)),
                    RKind::Struct => Kind::SeqStruct(ref_rust_name(r)),
                }
            }
            RFieldType::Seq(..) => {
                return Err("sequence-of-sequence unsupported by chain emitter".into())
            }
            other => Kind::SeqInt(
                int_elem_tokens(other).ok_or("unsupported sequence element type")?,
            ),
        },
    })
}

// ---- per-struct module -----------------------------------------------------------------------------

/// One field's five generated pieces.
struct FieldGen {
    trait_decl: TokenStream,
    fwd: TokenStream,
    absent: TokenStream,
    identity: TokenStream,
    zst: TokenStream,
    zst_ident: Ident,
}

fn emit_module(model: &Model, t: &RType, rust_name: &str) -> Result<TokenStream, String> {
    let modid = mod_ident(rust_name);
    let src_trait = src_trait_ident(rust_name);
    let concrete = Ident::new(rust_name, Span::call_site());
    let doc = format!(
        "Field chain for `{}::{}` — {}:{}",
        t.module, t.name, "mil-std-3071_data_model.idl", t.idl_line
    );

    let mut gens = Vec::new();
    for (i, f) in t.fields.iter().enumerate() {
        gens.push(emit_field(model, t, f, i, &src_trait)?);
    }

    let trait_decls = gens.iter().map(|g| &g.trait_decl);
    let fwds = gens.iter().map(|g| &g.fwd);
    let absents = gens.iter().map(|g| &g.absent);
    let identities = gens.iter().map(|g| &g.identity);
    let zsts = gens.iter().map(|g| &g.zst);

    // Chain = Node<F0, Node<F1, ... Nil>>, folded from the back (IDL order preserved).
    let mut chain = quote!(Nil);
    for g in gens.iter().rev() {
        let z = &g.zst_ident;
        chain = quote!(Node<#z, #chain>);
    }

    Ok(quote! {
        #[doc = #doc]
        pub mod #modid {
            use crate::fields::*;

            /// Accessor view of the topic payload — implemented by the concrete generated struct
            /// (identity) and by any borrowed source binding that can produce the same fields.
            pub trait #src_trait {
                #(#trait_decls)*
            }

            impl<'r, S: #src_trait + ?Sized> #src_trait for &'r S {
                #(#fwds)*
            }

            impl #src_trait for Absent {
                #(#absents)*
            }

            impl #src_trait for crate::generated::#concrete {
                #(#identities)*
            }

            #(#zsts)*

            /// The type-level field list, in IDL declaration order.
            pub type Chain = #chain;
        }
    })
}

fn emit_field(
    model: &Model,
    t: &RType,
    f: &RField,
    index: usize,
    src_trait: &Ident,
) -> Result<FieldGen, String> {
    let kind = classify(model, &f.ty)
        .map_err(|e| format!("{}.{}: {e}", t.name, f.idl_name))?;
    let m = safe_ident(&f.name);
    let has_m = safe_ident(&format!("has_{}", f.name));
    let field_pascal = pascal(&f.name);
    let zst_ident = Ident::new(&format!("{field_pascal}Field"), Span::call_site());
    let order = Literal::u16_unsuffixed(index as u16);
    let name = &f.name;
    let key = format!("\"{}\":", f.name);
    let opt = f.optional;

    // Scalar accessor return type (None for the GAT/RPITIT struct shapes, handled below).
    let scalar_ret: Option<TokenStream> = match &kind {
        Kind::Str => Some(quote!(&str)),
        Kind::Int => Some(quote!(i64)),
        Kind::Bool => Some(quote!(bool)),
        Kind::F32 | Kind::F64 => Some(quote!(FloatVal)),
        Kind::Enum(e) => {
            let eid = Ident::new(e, Span::call_site());
            Some(quote!(crate::generated::#eid))
        }
        Kind::SeqStr(n) => {
            let n = Literal::usize_unsuffixed(*n as usize);
            Some(quote!(&[heapless::String<#n>]))
        }
        Kind::SeqF32 => Some(quote!(&[f32])),
        Kind::SeqF64 => Some(quote!(&[f64])),
        Kind::SeqBool => Some(quote!(&[bool])),
        Kind::SeqInt(elem) => Some(quote!(&[#elem])),
        Kind::SeqEnum(e) => {
            let eid = Ident::new(e, Span::call_site());
            Some(quote!(&[crate::generated::#eid]))
        }
        Kind::Struct(_) | Kind::SeqStruct(_) => None,
    };

    // --- accessor trait / forwarding / Absent / identity, by shape ---
    let (trait_decl, fwd, absent, identity) = match &kind {
        Kind::Struct(n) => {
            let gat = Ident::new(&field_pascal, Span::call_site());
            let nmod = mod_ident(n);
            let nsrc = src_trait_ident(n);
            let nid = Ident::new(n, Span::call_site());
            if opt {
                (
                    quote! {
                        type #gat<'a>: super::#nmod::#nsrc where Self: 'a;
                        fn #m(&self) -> Option<Self::#gat<'_>>;
                    },
                    quote! {
                        type #gat<'a> = S::#gat<'a> where Self: 'a;
                        fn #m(&self) -> Option<Self::#gat<'_>> { (**self).#m() }
                    },
                    quote! {
                        type #gat<'a> = Absent where Self: 'a;
                        fn #m(&self) -> Option<Self::#gat<'_>> { match *self {} }
                    },
                    quote! {
                        type #gat<'a> = &'a crate::generated::#nid where Self: 'a;
                        fn #m(&self) -> Option<Self::#gat<'_>> { self.#m.as_ref() }
                    },
                )
            } else {
                (
                    quote! {
                        type #gat<'a>: super::#nmod::#nsrc where Self: 'a;
                        fn #m(&self) -> Self::#gat<'_>;
                    },
                    quote! {
                        type #gat<'a> = S::#gat<'a> where Self: 'a;
                        fn #m(&self) -> Self::#gat<'_> { (**self).#m() }
                    },
                    quote! {
                        type #gat<'a> = Absent where Self: 'a;
                        fn #m(&self) -> Self::#gat<'_> { match *self {} }
                    },
                    quote! {
                        type #gat<'a> = &'a crate::generated::#nid where Self: 'a;
                        fn #m(&self) -> Self::#gat<'_> { &self.#m }
                    },
                )
            }
        }
        Kind::SeqStruct(e) => {
            let gat = Ident::new(&format!("{field_pascal}Item"), Span::call_site());
            let emod = mod_ident(e);
            let esrc = src_trait_ident(e);
            let eid = Ident::new(e, Span::call_site());
            let has_decl = if opt {
                quote! { fn #has_m(&self) -> bool; }
            } else {
                quote! {}
            };
            let has_fwd = if opt {
                quote! { fn #has_m(&self) -> bool { (**self).#has_m() } }
            } else {
                quote! {}
            };
            let has_absent = if opt {
                quote! { fn #has_m(&self) -> bool { match *self {} } }
            } else {
                quote! {}
            };
            let (has_identity, iter_identity) = if opt {
                (
                    quote! { fn #has_m(&self) -> bool { self.#m.is_some() } },
                    quote! { self.#m.as_deref().unwrap_or(&[]).iter() },
                )
            } else {
                (quote! {}, quote! { self.#m.iter() })
            };
            (
                quote! {
                    type #gat<'a>: super::#emod::#esrc where Self: 'a;
                    #has_decl
                    fn #m(&self) -> impl Iterator<Item = Self::#gat<'_>> + '_;
                },
                quote! {
                    type #gat<'a> = S::#gat<'a> where Self: 'a;
                    #has_fwd
                    fn #m(&self) -> impl Iterator<Item = Self::#gat<'_>> + '_ { (**self).#m() }
                },
                quote! {
                    type #gat<'a> = Absent where Self: 'a;
                    #has_absent
                    fn #m(&self) -> impl Iterator<Item = Self::#gat<'_>> + '_ { core::iter::empty() }
                },
                quote! {
                    type #gat<'a> = &'a crate::generated::#eid where Self: 'a;
                    #has_identity
                    fn #m(&self) -> impl Iterator<Item = Self::#gat<'_>> + '_ { #iter_identity }
                },
            )
        }
        // Scalar-ish shapes (incl. scalar/enum/string sequences, which return slices).
        _ => {
            let ret = scalar_ret.clone().expect("scalar shapes have a return type");
            let is_seq = matches!(
                kind,
                Kind::SeqStr(_)
                    | Kind::SeqF32
                    | Kind::SeqF64
                    | Kind::SeqBool
                    | Kind::SeqInt(_)
                    | Kind::SeqEnum(_)
            );
            // Optional SCALARS wrap in Option; optional SEQUENCES keep the slice return (empty
            // when absent) and add `has_x` for the present/absent distinction.
            let ret_full = if opt && !is_seq {
                quote!(Option<#ret>)
            } else {
                ret.clone()
            };
            let has_decl = if opt && is_seq {
                quote! { fn #has_m(&self) -> bool; }
            } else {
                quote! {}
            };
            let has_fwd = if opt && is_seq {
                quote! { fn #has_m(&self) -> bool { (**self).#has_m() } }
            } else {
                quote! {}
            };
            let has_absent = if opt && is_seq {
                quote! { fn #has_m(&self) -> bool { match *self {} } }
            } else {
                quote! {}
            };
            let has_identity = if opt && is_seq {
                quote! { fn #has_m(&self) -> bool { self.#m.is_some() } }
            } else {
                quote! {}
            };
            let identity_body = identity_scalar_body(&kind, &m, opt);
            (
                quote! {
                    #has_decl
                    fn #m(&self) -> #ret_full;
                },
                quote! {
                    #has_fwd
                    fn #m(&self) -> #ret_full { (**self).#m() }
                },
                quote! {
                    #has_absent
                    fn #m(&self) -> #ret_full { match *self {} }
                },
                quote! {
                    #has_identity
                    fn #m(&self) -> #ret_full { #identity_body }
                },
            )
        }
    };

    // --- Field ZST emit body ---
    let value_emit = value_emit_tokens(&kind, &m);
    let emit_body = if opt {
        match &kind {
            Kind::Struct(_) | Kind::Enum(_) | Kind::Str | Kind::Int | Kind::Bool | Kind::F32
            | Kind::F64 => {
                let opt_value_emit = opt_value_emit_tokens(&kind);
                quote! {
                    let Some(v) = src.#m() else { return; };
                    emit_key(<Self as Field<Src>>::KEY, sink, first);
                    #opt_value_emit
                }
            }
            // Optional sequences: absent -> nothing; present (even empty) -> `key:[...]`.
            _ => quote! {
                if !src.#has_m() { return; }
                emit_key(<Self as Field<Src>>::KEY, sink, first);
                #value_emit
            },
        }
    } else {
        quote! {
            emit_key(<Self as Field<Src>>::KEY, sink, first);
            #value_emit
        }
    };

    let zst = quote! {
        pub struct #zst_ident;
        impl<Src: #src_trait + ?Sized> Field<Src> for #zst_ident {
            const ORDER: u16 = #order;
            const NAME: &'static str = #name;
            const KEY: &'static str = #key;
            fn emit<S: JsonSink>(src: &Src, sink: &mut S, first: &mut bool) {
                #emit_body
            }
        }
    };

    Ok(FieldGen {
        trait_decl,
        fwd,
        absent,
        identity,
        zst,
        zst_ident,
    })
}

/// Identity-impl body for the scalar shapes (plain reads off the concrete generated struct).
fn identity_scalar_body(kind: &Kind, m: &Ident, opt: bool) -> TokenStream {
    match kind {
        Kind::Str => {
            if opt {
                quote! { self.#m.as_deref() }
            } else {
                quote! { self.#m.as_str() }
            }
        }
        Kind::Int => {
            if opt {
                quote! { self.#m.map(|v| v as i64) }
            } else {
                quote! { self.#m as i64 }
            }
        }
        Kind::Bool | Kind::Enum(_) => quote! { self.#m },
        Kind::F32 => {
            if opt {
                quote! { self.#m.map(FloatVal::F32) }
            } else {
                quote! { FloatVal::F32(self.#m) }
            }
        }
        Kind::F64 => {
            if opt {
                quote! { self.#m.map(FloatVal::F64) }
            } else {
                quote! { FloatVal::F64(self.#m) }
            }
        }
        // Slices: deref-coerce the heapless::Vec (or the Option's deref) to the element slice.
        _ => {
            if opt {
                quote! { self.#m.as_deref().unwrap_or(&[]) }
            } else {
                quote! { &self.#m }
            }
        }
    }
}

/// Emit tokens rendering the REQUIRED (or present-sequence) value of `src.#m()` into the sink.
fn value_emit_tokens(kind: &Kind, m: &Ident) -> TokenStream {
    match kind {
        Kind::Str => quote! { emit_str_value(sink, src.#m()); },
        Kind::Int => quote! { sink.raw_int(src.#m()); },
        Kind::Bool => quote! { sink.str(if src.#m() { "true" } else { "false" }); },
        Kind::F32 | Kind::F64 => quote! { emit_num(sink, src.#m()); },
        Kind::Enum(_) => quote! {
            sink.str("\"");
            sink.str(src.#m().wire_str());
            sink.str("\"");
        },
        Kind::Struct(n) => {
            let nmod = mod_ident(n);
            quote! { emit_object::<_, super::#nmod::Chain, _>(&src.#m(), sink); }
        }
        Kind::SeqStruct(e) => {
            let emod = mod_ident(e);
            seq_emit(m, quote! { emit_object::<_, super::#emod::Chain, _>(&item, sink); }, false)
        }
        Kind::SeqStr(_) => seq_emit(m, quote! { emit_str_value(sink, item); }, true),
        Kind::SeqF32 => seq_emit(m, quote! { sink.f32(*item); }, true),
        Kind::SeqF64 => seq_emit(m, quote! { sink.f64(*item); }, true),
        Kind::SeqBool => {
            seq_emit(m, quote! { sink.str(if *item { "true" } else { "false" }); }, true)
        }
        Kind::SeqInt(_) => seq_emit(m, quote! { sink.raw_int(*item as i64); }, true),
        Kind::SeqEnum(_) => seq_emit(
            m,
            quote! {
                sink.str("\"");
                sink.str(item.wire_str());
                sink.str("\"");
            },
            true,
        ),
    }
}

/// Emit tokens for a PRESENT optional scalar already unwrapped into `v` by the let-else.
fn opt_value_emit_tokens(kind: &Kind) -> TokenStream {
    match kind {
        Kind::Str => quote! { emit_str_value(sink, v); },
        Kind::Int => quote! { sink.raw_int(v); },
        Kind::Bool => quote! { sink.str(if v { "true" } else { "false" }); },
        Kind::F32 | Kind::F64 => quote! { emit_num(sink, v); },
        Kind::Enum(_) => quote! {
            sink.str("\"");
            sink.str(v.wire_str());
            sink.str("\"");
        },
        Kind::Struct(n) => {
            let nmod = mod_ident(n);
            quote! { emit_object::<_, super::#nmod::Chain, _>(&v, sink); }
        }
        _ => unreachable!("optional sequences use the has_x path"),
    }
}

/// A `[` … `]` loop over `src.#m()` — slice shapes iterate the slice, struct sequences iterate the
/// RPITIT iterator directly.
fn seq_emit(m: &Ident, per_item: TokenStream, slice: bool) -> TokenStream {
    let iter = if slice {
        quote! { src.#m().iter() }
    } else {
        quote! { src.#m() }
    };
    quote! {
        sink.str("[");
        let mut first_item = true;
        for item in #iter {
            if !first_item { sink.str(","); }
            first_item = false;
            #per_item
        }
        sink.str("]");
    }
}
